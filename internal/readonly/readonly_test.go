func TestErrorsSayWhy(t *testing.T) {
	for cmd, want := range map[string]string{
		"rm x":              "not recognized",
		"ls > out":          "not allowed",
		"find . -delete":    "-delete",
		"cat ~/.ssh/id_rsa": "secrets",
		"git log":           "--no-pager",
	} {
		err := Check(cmd)
		if err == nil || !contains(err.Error(), want) {
			t.Errorf("Check(%q) = %v, debería mencionar %q", cmd, err, want)
		}
	}
}

func contains(s, sub string) bool {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return true
		}
	}
	return false
}
