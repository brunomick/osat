/** La paleta que corresponde al ajuste. "auto" (igual que la interfaz) usa la del tema de la interfaz: osat oscuro o claro, o la del mismo nombre. */
export function resolve(name: TermThemeSetting, ui: UiTheme): TermTheme {
  if (name === 'auto') return termThemes[termThemeOf(ui)] ?? termThemes['osat-dark']
  return termThemes[name] ?? termThemes['osat-dark'] // un nombre desconocido (no debería llegar) no deja la terminal sin colores
}
